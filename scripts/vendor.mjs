import { writeFileSync, mkdirSync } from 'node:fs';

const FONT_BASE = 'https://assets-bucket.deadlock-api.com/assets-api-res/fonts/';
const LOGO_BASE = 'https://assets-bucket.deadlock-api.com/assets-api-res/images/main_menu/';

const FONTS = [
  'radiance-semibold.otf',
  'radiance-bold.otf',
  'radiancem-semibold.otf',
  'reaver-bold.otf'
];

// Composite = outer + inner_noeye + eye. deadlock_logo_inner.svg (10 paths)
// is the inner form WITH the eye baked in; we want the eye separable, so skip it.
const LOGO = {
  'outer.svg': 'deadlock_logo_outer.svg',
  'inner_noeye.svg': 'deadlock_logo_inner_noeye.svg',
  'eye.svg': 'deadlock_logo_eye.svg'
};

async function grab(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(dest, buf);
  console.log(`  ${dest}  ${buf.length} bytes`);
}

mkdirSync('overlay/fonts', { recursive: true });
mkdirSync('overlay/logo', { recursive: true });
mkdirSync('overlay/heroes', { recursive: true });

console.log('fonts:');
for (const f of FONTS) await grab(FONT_BASE + f, `overlay/fonts/${f}`);

console.log('logo layers:');
for (const [dest, src] of Object.entries(LOGO)) await grab(LOGO_BASE + src, `overlay/logo/${dest}`);

// Hero icons, named by hero id so a renderer needs no manifest — it can resolve
// heroes/<heroId>.webp directly.
//
// The chiron's Hero turn renders these, replacing what used to be a raw
// `Hero 20` — the only place a database id reached the screen. Only heroes that
// ship a small icon are vendored, so the renderer expects a miss and falls back
// to the name from the map written below.
const HEROES_URL = 'https://api.deadlock-api.com/v1/assets/heroes';
const heroes = await (await fetch(HEROES_URL)).json();
const withIcon = heroes.filter(h => !h.disabled && h.images?.icon_image_small_webp);

// The name map, written whether or not an icon exists for each hero: the
// no-icon case is exactly when the chiron needs a name to fall back to, and
// five live heroes ship no small icon. Emitted here rather than hand-written so
// a roster change cannot leave it stale — the same reason tokens.css is
// generated. See tests/heroes.test.js.
const named = heroes.filter(h => !h.disabled && Number.isInteger(h.id) && h.name)
  .sort((a, b) => a.id - b.id);
const NL = String.fromCharCode(10);
writeFileSync('overlay/heroes.js', [
  '/* GENERATED by scripts/vendor.mjs — do not edit by hand.',
  `   Source: ${HEROES_URL}`,
  '   Regenerate after a Deadlock patch: npm run vendor */',
  '',
  '/**',
  ' * Hero id -> display name.',
  ' *',
  ' * The chiron shows a hero ICON, resolved as heroes/<id>.webp. These names are',
  ' * what that image says when it cannot be seen: its alt text, and the text that',
  ' * replaces it for a hero whose icon is not vendored (only heroes shipping a',
  ' * small icon are downloaded). Without them the fallback would be the raw',
  ' * `Hero 20` this replaced.',
  ' *',
  ' * Every non-disabled hero is listed, including those without an icon — the',
  ' * no-icon case is exactly when a name is needed.',
  ' */',
  'export const HERO_NAMES = {',
  named.map(h => `  ${h.id}: ${JSON.stringify(h.name)},`).join(NL),
  '};',
  '',
  '/** The name, or a last-resort label that still beats a bare number. */',
  'export const heroName = id => HERO_NAMES[id] ?? (Number.isInteger(id) ? `Hero ${id}` : null);',
  ''
].join(NL));
console.log(`overlay/heroes.js        ${named.length} hero names`);

console.log(`hero icons (${withIcon.length} of ${heroes.length} have one):`);
let bytes = 0;
for (const h of withIcon) {
  const res = await fetch(h.images.icon_image_small_webp);
  if (!res.ok) { console.warn(`  skip ${h.id} ${h.name} -> ${res.status}`); continue; }
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(`overlay/heroes/${h.id}.webp`, buf);
  bytes += buf.length;
}
console.log(`  ${withIcon.length} icons, ${(bytes / 1024).toFixed(0)} KB total`);
